# 保存文件并上传github流程
# 1.修改完成后按Ctrl + S 保存
# 2.在终端输入 "git add '文件名' " 
#   例如 "git add hello.py "
#   添加文件夹内所有文件 "git add . "
# 3.在终端输入 "git commit -m "修改内容" "
#   例如 "git commit -m "增加了某某功能" "
# 4.在终端输入 "git push "
# 网页端按f5刷新页面

# 将你的新项目关联至github
# 1.登录github创建 New repository
# 2.在终端输入"git config --global user.name"
# 3.在终端输入"git config --global user.email"
# 4.在终端输入"git init"
# 5.完成第一大块内容
# 6.在终端输入"git remote add origin https://github.com/用户名/仓库名.git"
# 7.在终端输入"git push -u origin main"
